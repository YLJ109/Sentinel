_HL_TARGETS: list[str] = ["他", "她", "你", "他们", "她们", "你们", "人", "同学", "同桌", "班长"]

_HL_MODES: list[str] = ["", "狠狠地", "用力", "使劲", "一直", "天天", "又", "还想", "偷偷", "故意"]


def _expand() -> list[str]:
    """由动作 × 对象（× 方式）生成 highlight 档词条。

    这些组合是真实可能出现的表述，但**单独一句无法与正常互动区分**
    （"推他一下"可能是玩闹，"拽了一下"可能是帮忙），所以只做高亮提示，
    供人工复核时快速定位可疑片段，不参与报警判定。
    """
    out: list[str] = []
    for act in _HL_ACTIONS:
        for tgt in _HL_TARGETS:
            out.append(f"{act}{tgt}")
            out.append(f"{act}{tgt}一下")
            out.append(f"{act}{tgt}了")
        # 被动/受害视角："被人推""被他拽" —— 学生描述遭遇时最常用的说法
        out.append(f"被{act}")
        out.append(f"被人{act}")
        out.append(f"被他{act}")
        out.append(f"被她{act}")
    for mode in _HL_MODES:
        if not mode:
            continue
        for act in _HL_ACTIONS:
            for tgt in _HL_TARGETS[:5]:
                out.append(f"{mode}{act}{tgt}")
    return out


